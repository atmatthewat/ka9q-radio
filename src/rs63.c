// Reed-Solomon codes over GF(64) with errors and erasures, the P25 codes among them,
// and the BCH(63,16,23) code of the P25 NID decoded as a binary subcode of one.
// The decoding is Phil Karn's general Reed-Solomon decoder from libfec (decode_rs_char.c,
// init_rs_char.c); this file maps our symbol order and shortening onto it and keeps our
// rules for accepting a correction
// Copyright 2026, Matthew Kaufman, KA6SQG
#include <assert.h>
#include <pthread.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "rs63.h"

// libfec's 8-bit-or-less Reed-Solomon codec (declared in its fec.h)
void *init_rs_char(int symsize,int gfpoly,int fcr,int prim,int nroots,int pad);
int decode_rs_char(void *rs,unsigned char *data,int *eras_pos,int no_eras);

// GF(64) generated by x^6 + x + 1, primitive element alpha = x
enum {
  GF_M = 6,
  GF_N = 63,           // field period, and the length of every P25 RS code before shortening
  GF_POLY = 0x43,
  ALPHA_POW_SPAN = 4,  // alpha_pow[e] = alpha^(e mod 63) for e < 4 * 63: no division in the loops
  RS_MAXPAR = 28,      // most parity symbols of any P25 code (RS(63,35))
};

static int Alpha_to[GF_N+1];             // alpha^i, i = 0..62
static int Index_of[GF_N+1];             // log; Index_of[0] = -1
static int Alpha_pow[ALPHA_POW_SPAN * GF_N];

static pthread_once_t Once = PTHREAD_ONCE_INIT;

// libfec codecs, made once and then only read (decode_rs_char() does not write to them):
// one unshortened code per parity count, and the shortened P25 codes with their padding
// so their syndromes and search skip the zero symbols. Any other shortened length uses the
// unshortened codec, the zero symbols included
static void *Rs_full[RS_MAXPAR+1];
static struct {
  int parity;
  int length;
  void *rs;
} Rs_short[] = {
  {12, 24, NULL}, // RS(24,12,13)
  {8, 24, NULL},  // RS(24,16,9)
  {16, 36, NULL}, // RS(36,20,17)
  {28, 44, NULL}, // RS(44,16,29)
};

static void init_tables(void){
  int x = 1;
  for(int i = 0; i < GF_N; i++){
    Alpha_to[i] = x;
    Index_of[x] = i;
    x <<= 1;
    if(x & (1 << GF_M))
      x ^= GF_POLY;
  }
  Alpha_to[GF_N] = 0; // unused
  Index_of[0] = -1;
  for(int e = 0; e < ALPHA_POW_SPAN * GF_N; e++)
    Alpha_pow[e] = Alpha_to[e % GF_N];
  // symbol size 6, field polynomial x^6 + x + 1, roots alpha^1 .. alpha^parity
  for(int p = 1; p <= RS_MAXPAR; p++){
    Rs_full[p] = init_rs_char(GF_M,GF_POLY,1,1,p,0);
    if(Rs_full[p] == NULL)
      abort();
  }
  for(size_t i = 0; i < sizeof Rs_short / sizeof Rs_short[0]; i++){
    Rs_short[i].rs = init_rs_char(GF_M,GF_POLY,1,1,Rs_short[i].parity,GF_N - Rs_short[i].length);
    if(Rs_short[i].rs == NULL)
      abort();
  }
}
static inline void init(void){
  pthread_once(&Once,init_tables);
}

// ---------------------------------------------------------------------------
// Reed-Solomon over GF(64)

// True if all syndromes S1..S_parity of the word are zero
static bool is_codeword(int const *sym,int parity){
  for(int r = 1; r <= parity; r++){
    int acc = 0;
    int ij = 0; // (r * j) mod 63, stepped with j
    for(int j = 0; j < GF_N; j++){
      if(sym[j] != 0)
        acc ^= Alpha_pow[Index_of[sym[j]] + ij];
      ij += r;
      if(ij >= GF_N)
        ij -= GF_N;
    }
    if(acc != 0)
      return false;
  }
  return true;
}
bool rs63_is_codeword(uint8_t const sym[GF_N],int parity){
  assert(sym != NULL);
  assert(parity >= 1 && parity < GF_N);
  init();
  int s[GF_N];
  for(int i = 0; i < GF_N; i++)
    s[i] = sym[i] & GF_N;
  return is_codeword(s,parity);
}

// The decoded word as the caller sees it. In binary mode (the BCH code, decoded as the binary
// subcode of an RS code) each symbol is a bit, and a non-binary correction is truncated to 1;
// the codeword checks that follow then reject it
static void commit(int *out,int const *poly,bool binary){
  for(int i = 0; i < GF_N; i++)
    out[i] = binary ? (poly[i] != 0) : (poly[i] & GF_N);
}

// Errors-and-erasures decode by libfec. sym[] is updated only on success. libfec takes the
// highest power first and numbers positions in the unshortened block from the highest power,
// so coefficient i (x^i) is its position 62 - i, and data[j] of a block of n symbols is x^(n-1-j).
// It accepts any errata locator whose roots it all finds, so we add our own rules: at most
// (parity - erasures) / 2 errors, no correction in the shortened code's zero padding, and the
// result must be a codeword (of the binary subcode in binary mode). It also returns 0, no
// correction, when the locator comes out of degree 0 for a word that is not a codeword, so a
// codeword is recognised here first and 0 from libfec is a failure
static bool rs_erasures(int *sym,int parity,int length,bool binary,int const *erasures,int t){
  if(t > parity)
    return false;
  if(is_codeword(sym,parity))
    return true; // already a codeword
  void *rs = Rs_full[parity];
  int n = GF_N;
  for(size_t i = 0; i < sizeof Rs_short / sizeof Rs_short[0]; i++){
    if(Rs_short[i].parity == parity && Rs_short[i].length == length){
      rs = Rs_short[i].rs;
      n = length;
      break;
    }
  }
  for(int i = length; i < GF_N && n < GF_N; i++){
    if(sym[i] != 0)
      n = GF_N; // not zero where the code is shortened: decode it all, and so reject it
  }
  if(n == GF_N)
    rs = Rs_full[parity];
  unsigned char data[GF_N];
  for(int j = 0; j < n; j++)
    data[j] = (unsigned char)sym[n-1-j];
  int pos[RS_MAXPAR];
  for(int i = 0; i < t; i++)
    pos[i] = GF_N - 1 - erasures[i];
  int const count = decode_rs_char(rs,data,pos,t);
  if(count <= 0)
    return false; // the locator does not split, or (0) has degree 0 though the word is no codeword
  if(2 * (count - t) + t > parity)
    return false; // more errors than the code corrects
  for(int i = 0; i < count; i++){
    if(GF_N - 1 - pos[i] >= length)
      return false; // a "correction" in the zero padding: not a codeword of the real code
  }
  int poly[GF_N];
  memcpy(poly,sym,sizeof poly);
  for(int j = 0; j < n; j++)
    poly[n-1-j] = data[j];
  int out[GF_N];
  commit(out,poly,binary);
  if(!is_codeword(out,parity))
    return false;
  memcpy(sym,out,sizeof out);
  return true;
}

int rs63_decode(uint8_t sym[GF_N],int parity,int length,int const *erasures,int nerasures){
  assert(sym != NULL);
  assert(parity >= 1 && parity <= RS_MAXPAR);
  assert(length > parity && length <= GF_N);
  assert(nerasures >= 0 && (nerasures == 0 || erasures != NULL));
  init();
  int w[GF_N];
  for(int i = 0; i < GF_N; i++)
    w[i] = sym[i] & GF_N;
  for(int i = 0; i < nerasures; i++)
    assert(erasures[i] >= 0 && erasures[i] < GF_N);

  if(!rs_erasures(w,parity,length,false,erasures,nerasures))
    return -1;
  int changed = 0;
  for(int i = 0; i < GF_N; i++){
    if(w[i] != (sym[i] & GF_N))
      changed++;
    sym[i] = w[i];
  }
  return changed;
}

// ---------------------------------------------------------------------------
// BCH(63,16,23), the P25 NID

enum { BCH_N = 63, BCH_REDUNDANCY = 22 }; // 22 syndromes (designed distance 23)
static uint64_t const Bch_generator = 06331141367235453ULL; // bit i = coefficient of x^i, degree 47

static uint64_t bch_remainder(uint64_t w){
  for(int b = 62; b >= 47; b--){
    if((w >> b) & 1)
      w ^= Bch_generator << (b - 47);
  }
  return w;
}

int bch_63_16_decode(uint8_t bits[BCH_N],int const *erasures,int nerasures){
  assert(bits != NULL);
  assert(nerasures >= 0 && (nerasures == 0 || erasures != NULL));
  init();
  // Bit k is the coefficient of x^(62-k), i.e. RS position 62 - k
  int w[GF_N];
  uint64_t received = 0;
  for(int k = 0; k < BCH_N; k++){
    w[62-k] = bits[k] ? 1 : 0;
    if(bits[k])
      received |= 1ULL << (62 - k);
  }
  int rev[GF_N + 1];
  int t = 0;
  uint64_t erased = 0;
  for(int i = 0; i < nerasures; i++){
    if(erasures[i] >= 0 && erasures[i] < BCH_N){
      if(t >= BCH_REDUNDANCY)
        return -1; // too many
      rev[t++] = 62 - erasures[i];
      erased |= 1ULL << (62 - erasures[i]);
    }
  }
  if(!rs_erasures(w,BCH_REDUNDANCY,GF_N,true,rev,t))
    return -1;

  // Only a BCH codeword is a decode
  uint64_t corrected = 0;
  for(int i = 0; i < GF_N; i++){
    if(w[i])
      corrected |= 1ULL << i;
  }
  if(bch_remainder(corrected) != 0)
    return -1;
  int const errors = __builtin_popcountll((received ^ corrected) & ~erased);
  if(2 * errors + t > BCH_REDUNDANCY)
    return -1;
  for(int k = 0; k < BCH_N; k++)
    bits[k] = (corrected >> (62 - k)) & 1;
  return __builtin_popcountll(received ^ corrected);
}

int bch_63_16_decode_soft(uint8_t bits[BCH_N],float const confidence[32],bool const lsb_ambiguous[32],float threshold){
  assert(bits != NULL && confidence != NULL && lsb_ambiguous != NULL);
  int r = bch_63_16_decode(bits,NULL,0);
  if(r >= 0)
    return r;

  // Dibits, weakest first (stable: equal confidences in dibit order)
  int order[32];
  for(int j = 0; j < 32; j++){
    int i = j;
    while(i > 0 && confidence[order[i-1]] > confidence[j]){
      order[i] = order[i-1];
      i--;
    }
    order[i] = j;
  }
  int erasures[BCH_REDUNDANCY];
  int n = 0;
  for(int k = 0; k < 32; k++){
    int const j = order[k];
    if(confidence[j] >= threshold || n >= BCH_REDUNDANCY)
      break;
    int const bit = 2 * j + (lsb_ambiguous[j] ? 1 : 0);
    if(bit < BCH_N)
      erasures[n++] = bit; // bit 63 is the NID parity bit, not part of the BCH word
  }
  if(n == 0)
    return -1;
  return bch_63_16_decode(bits,erasures,n);
}
